# Unit 4 - Q4(1): math library

import math

num = float(input("Enter a number: "))
int_num = int(num)

print("Square root:", math.sqrt(num))
print("Factorial of", int_num, ":", math.factorial(int_num))
print("Power (2 ^ 10):", math.pow(2, 10))
print("Ceiling:", math.ceil(num))
print("Floor:", math.floor(num))
